_TECHNICAL_ONLY = re.compile(r"^[a-z0-9_.:+/@=-]+$")


def _looks_technical_only(text: str) -> bool:
    stripped = text.strip()
    if not stripped:
        return True
    if stripped.startswith(("http://", "https://", "/", "\\\\", "E:\\", "C:\\")):
        return True
    if _TECHNICAL_ONLY.fullmatch(stripped) and stripped == stripped.lower():
        return True
    # Hashes / IDs / command-like placeholders should never be linguistically changed.
    if re.fullmatch(r"[0-9a-fA-F]{16,}", stripped):
        return True
    return False


def tr(text: object) -> str:
    """Return localized user-facing text.

    English strings remain the canonical source. Danish is the default.
    Missing exact translations are handled by conservative phrase translation;
    machine values, identifiers, paths and URLs are left untouched.
    """
    source = "" if text is None else str(text)
    if _current_language != "da":
        return source

    exact = _DA.get(source)
    if exact is not None:
        return exact

    for source_prefix, target_prefix in _DA_PREFIXES:
        if source.startswith(source_prefix):
            remainder = source[len(source_prefix):]
            return target_prefix + tr(remainder)

    if _looks_technical_only(source):
        return source

    result = source
    for english, danish in _DA_PHRASES:
        if english in result:
            result = result.replace(english, danish)
    return result
