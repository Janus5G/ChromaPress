def test_ai_deployable_output_excludes_internal_manifest_and_has_no_fingerprint():
    from chromapress.services.part6 import review_generated_project, ai_app_payload, validate_ai_app_payload

    review = review_generated_project(_manifest_project())
    assert review["status"] == "PASS"
    payload = ai_app_payload(
        review,
        _target_context(),
        provider="openai",
        model="gpt-5.6-sol",
        toolchain="Auto",
        prompt="Build a neutral demo",
        human_review_acknowledged=True,
    )
    assert payload["internal_control_files"] == ["chromapress-app.json"]
    assert payload["internal_control_files_deployed"] is False
    assert payload["generated_output_fingerprint_policy"] == "neutral_no_chromapress_markers"
    assert payload["generated_output_telemetry"] is False
    assert payload["generated_output_shared_chromapress_runtime"] is False
    paths = [row["path"] for row in payload["deployable_project_files"]]
    assert paths == ["app.py"]
    serialized = json.dumps(payload["deployable_project_files"]).casefold()
    assert "chromapress" not in serialized
    assert validate_ai_app_payload(payload)[0]


