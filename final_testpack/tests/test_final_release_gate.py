def test_release_sources_do_not_reintroduce_proprietary_license_markers():
    paths = [ROOT / "LICENSE", ROOT / "pyproject.toml"]
    paths.extend(p for p in SRC.rglob("*") if p.is_file() and p.suffix in {".py", ".txt", ".svg"})
    bad = []
    for path in paths:
        text = path.read_text(encoding="utf-8", errors="ignore")
        if "ChromaPress Proprietary License" in text or "All rights reserved" in text:
            bad.append(str(path.relative_to(ROOT)))
    assert bad == []
