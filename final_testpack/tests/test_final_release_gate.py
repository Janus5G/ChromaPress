from __future__ import annotations

import json
import os
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "src" / "chromapress"


def _manifest_project(app_body: str = "print('hello')\n") -> str:
    manifest = {
        "name": "Neutral Demo",
        "version": "1.0",
        "entrypoint": "app.py",
        "packages": [],
        "services": [],
        "permissions": [],
        "autostart": [],
        "desktop_integration": [],
        "security_implications": ["No network service"],
        "build": {"command": "python -m compileall .", "requires_network": False},
        "test": {"command": "python -m unittest", "requires_network": False},
    }
    return "--- chromapress-app.json ---\n" + json.dumps(manifest) + "\n--- app.py ---\n" + app_body


def _target_context() -> dict:
    return {
        "distribution": "Ubuntu",
        "version": "26.04",
        "architecture": "amd64",
        "desktop": "LXQt",
        "package_format": "deb",
        "package_manager": "apt/dpkg",
        "available_libraries": ["python3"],
        "installer_type": "Subiquity/Autoinstall",
        "source_sha256": "a" * 64,
        "scenario": "Desktop",
        "scenario_context": "",
    }


